/**
 * Generate `src/monaco/jsKeywords.ts` — the JS/TS reserved words used to color
 * keywords in the Strudel Monarch tokenizer.
 *
 * Why a generator instead of a hand-written list: Strudel patterns are
 * JavaScript, and the keyword set is JavaScript's, not ours to invent. Monaco
 * (`monaco-editor`, already a dependency and the runtime we self-host) ships
 * the authoritative Monarch grammar for JS/TS — we extract its `keywords`
 * array so the source of truth stays Monaco's grammar.
 *
 * We can't `import` that grammar at build time into the app bundle: its module
 * pulls in `editor.api.js` (Monaco core), which the editor package keeps
 * type-only / self-hosted. So we read the file as TEXT here (no execution, no
 * browser globals) and emit a pure-data `.ts` file.
 *
 * Regenerate after a monaco-editor bump:  node scripts/gen-js-keywords.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const tsGrammarPath = require.resolve(
  'monaco-editor/esm/vs/basic-languages/typescript/typescript.js',
)
const version = require('monaco-editor/package.json').version
const src = readFileSync(tsGrammarPath, 'utf8')

// Slice out the `keywords: [ … ]` array literal, then pull the quoted words.
// (There is a `//` comment inside the array, but it carries no quoted tokens,
//  so a quoted-string match skips it cleanly.)
const start = src.indexOf('keywords: [')
if (start < 0) throw new Error('could not find `keywords: [` in monaco grammar')
const end = src.indexOf(']', start)
if (end < 0) throw new Error('unterminated keywords array in monaco grammar')
const block = src.slice(start, end)
const extracted = [...block.matchAll(/["']([A-Za-z_$][\w$]*)["']/g)].map((m) => m[1])

// Monaco's list omits the literal values; add them so `true`/`false`/`null`/
// `undefined` also read as keywords. These are frozen JS literals, not a
// maintained vocabulary.
const LITERALS = ['true', 'false', 'null', 'undefined']
const words = [...new Set([...extracted, ...LITERALS])].sort()

if (words.length < 20) throw new Error(`suspiciously few keywords (${words.length})`)

const out = `// GENERATED by scripts/gen-js-keywords.mjs — do not edit by hand.
// JS/TS reserved words extracted from monaco-editor's own Monarch grammar
// (basic-languages/typescript \`language.keywords\`, v${version}) plus the JS
// literal values Monaco's list omits. The source of truth is Monaco's grammar,
// so we don't hand-maintain this list. Regenerate after a monaco-editor bump:
//   node scripts/gen-js-keywords.mjs
export const JS_KEYWORDS: readonly string[] = ${JSON.stringify(words, null, 2)}
`

const outUrl = new URL('../src/monaco/jsKeywords.ts', import.meta.url)
writeFileSync(outUrl, out)
console.log(`wrote ${words.length} keywords from monaco-editor@${version}`)
